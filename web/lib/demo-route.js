/** 마지막 점이 "방금"이 되도록 5분 간격으로 타임스탬프를 붙여 돌려준다. */
export function demoRows(intervalMinutes = 5) {
  const stepMs = intervalMinutes * 60_000;
  const startMs = Date.now() - (TRACK.length - 1) * stepMs;
  return TRACK.map((entry, index) => ({
    id: index + 1,
    session_code: 'demo',
    latitude: entry[0],
    longitude: entry[1],
    accuracy: entry[2],
    updated_at: new Date(startMs + index * stepMs).toISOString(),
  }));
}

